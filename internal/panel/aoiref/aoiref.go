// Prefix starts the /start parameter of a referral link: /start ref-<code>.
const Prefix = model.ReferralPrefix

// Referral states.
const (
	StatePending    = "pending"       // made, nothing bought yet
	StateTrial      = "trial_started" // the referral took the trial
	StatePaid       = "paid"          // paid, the reward waits for Hold
	StateRewarded   = "rewarded"      // the referrer got the days
	StateIneligible = "ineligible"    // refunded after the reward, or refused by hand
)

var (
	// ErrInvalid: no account has this code.
	ErrInvalid = model.ErrReferralInvalid
	codeRe     = regexp.MustCompile(`^[a-z0-9]{4,16}$`)
)

// Deps are what the programme works with.
type Deps struct {
	Store *store.Store
	Users *domain.Users
	// BotURL is https://t.me/<bot>, "" while the bot is not running.
	BotURL func(ctx context.Context) string
	// Notify tells an account something in the bot; nil: nobody is told.
	Notify func(ctx context.Context, tgID int64, text string)
	Now    func() time.Time
	Log    *slog.Logger
}

type Service struct {
	d Deps
	// RewardDays the referrer gets for a referral's first payment, after Hold.
	RewardDays int64
	Hold       time.Duration

	schemaMu sync.Mutex
	schemaOK bool
}

func New(d Deps) *Service {
	if d.Now == nil {
		d.Now = time.Now
	}
	if d.Log == nil {
		d.Log = slog.New(slog.DiscardHandler)
	}
	return &Service{d: d, RewardDays: 7, Hold: 24 * time.Hour}
}

const schema = `
CREATE TABLE IF NOT EXISTS aoi_ref_codes (
  tg_id      BIGINT PRIMARY KEY,
  code       TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS aoi_referrals (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_tg    BIGINT NOT NULL,
  referred_tg    BIGINT NOT NULL UNIQUE,
  code           TEXT NOT NULL,
  status         TEXT NOT NULL DEFAULT 'pending', -- pending | trial_started | paid | rewarded | ineligible
  payment_id     BIGINT,                          -- the referral's first payment
  paid_at        BIGINT,
  rewarded_at    BIGINT,
  reward_user_id BIGINT,                          -- the referrer's subscription extended; NULL: the bank
  reward_days    BIGINT NOT NULL DEFAULT 0,
  created_at     BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS aoi_referrals_referrer ON aoi_referrals (referrer_tg);
CREATE INDEX IF NOT EXISTS aoi_referrals_status ON aoi_referrals (status);
CREATE TABLE IF NOT EXISTS aoi_ref_bank (
  tg_id      BIGINT PRIMARY KEY, -- days earned while the referrer had no subscription
  days       BIGINT NOT NULL DEFAULT 0,
  updated_at BIGINT NOT NULL
);
`

// ensureSchema makes the tables once; a failure is tried again on the next call.
func (s *Service) ensureSchema(ctx context.Context) error {
	s.schemaMu.Lock()
	defer s.schemaMu.Unlock()
	if s.schemaOK {
		return nil
	}
	if _, err := s.d.Store.DB.ExecContext(ctx, schema); err != nil {
		return err
	}
	s.schemaOK = true
	return nil
}

const codeAlphabet = "abcdefghijklmnopqrstuvwxyz0123456789"

func newCode(n int) string {
	b := make([]byte, n)
	for i := range b {
		k, _ := rand.Int(rand.Reader, big.NewInt(int64(len(codeAlphabet))))
		b[i] = codeAlphabet[k.Int64()]
	}
	return string(b)
}

// Code is the account's referral code, made on first ask.
func (s *Service) Code(ctx context.Context, tgID int64) (string, error) {
	if err := s.ensureSchema(ctx); err != nil {
		return "", err
	}
	for range 12 {
		var code string
		err := s.d.Store.DB.QueryRowContext(ctx, "SELECT code FROM aoi_ref_codes WHERE tg_id = $1", tgID).Scan(&code)
		if err == nil {
			return code, nil
		}
		if !errors.Is(err, sql.ErrNoRows) {
			return "", err
		}
		// A code taken by another account, or this account's code made meanwhile: the next
		// round reads or tries again.
		if _, err := s.d.Store.DB.ExecContext(ctx,
			"INSERT INTO aoi_ref_codes (tg_id, code, created_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING",
			tgID, newCode(6), s.d.Now().Unix()); err != nil {
			return "", err
		}
	}
	return "", errors.New("referral code: no free code")
}

// Link is the account's referral link; "" while the bot is not running.
func (s *Service) Link(ctx context.Context, tgID int64) (string, error) {
	code, err := s.Code(ctx, tgID)
	if err != nil || s.d.BotURL == nil {
		return "", err
	}
	base := s.d.BotURL(ctx)
	if base == "" {
		return "", nil
	}
	return base + "?start=" + Prefix + code, nil
}

// Refer makes referredTg the referral of the code's owner, when it has nothing of its
// own yet and is nobody's referral. true: it is now.
func (s *Service) Refer(ctx context.Context, referredTg int64, code string) (bool, error) {
	if err := s.ensureSchema(ctx); err != nil {
		return false, err
	}
	code = strings.ToLower(strings.TrimSpace(code))
	if !codeRe.MatchString(code) {
		return false, ErrInvalid
	}
	var referrer int64
	err := s.d.Store.DB.QueryRowContext(ctx, "SELECT tg_id FROM aoi_ref_codes WHERE code = $1", code).Scan(&referrer)
	if errors.Is(err, sql.ErrNoRows) {
		return false, ErrInvalid
	}
	if err != nil || referrer == referredTg || referredTg <= 0 {
		return false, err
	}
	var had bool
	if err := s.d.Store.DB.QueryRowContext(ctx, `SELECT
		EXISTS (SELECT 1 FROM tg_links WHERE tg_id = $1) OR
		EXISTS (SELECT 1 FROM trials WHERE tg_id = $1) OR
		EXISTS (SELECT 1 FROM payments WHERE tg_id = $1 AND status IN ('paid', 'applied', 'refunded'))`,
		referredTg).Scan(&had); err != nil || had {
		return false, err
	}
	res, err := s.d.Store.DB.ExecContext(ctx, `INSERT INTO aoi_referrals (referrer_tg, referred_tg, code, created_at)
		VALUES ($1, $2, $3, $4) ON CONFLICT (referred_tg) DO NOTHING`, referrer, referredTg, code, s.d.Now().Unix())
	if err != nil {
		return false, err
	}
	n, _ := res.RowsAffected()
	if n == 1 {
		s.d.Log.Info("referral: made", "referrer", referrer, "referred", referredTg)
	}
	return n == 1, nil
}

// Stats is an account's programme as the bot shows it.
type Stats = model.ReferralStats

func (s *Service) Stats(ctx context.Context, tgID int64) (Stats, error) {
	link, err := s.Link(ctx, tgID)
	if err != nil {
		return Stats{}, err
	}
	st := Stats{Link: link}
	st.Code, _ = s.Code(ctx, tgID)
	err = s.d.Store.DB.QueryRowContext(ctx, `SELECT count(*),
		count(*) FILTER (WHERE status IN ('paid', 'rewarded')),
		count(*) FILTER (WHERE status = 'rewarded'),
		COALESCE(sum(reward_days) FILTER (WHERE status = 'rewarded'), 0),
		COALESCE((SELECT days FROM aoi_ref_bank WHERE tg_id = $1), 0)
		FROM aoi_referrals WHERE referrer_tg = $1`, tgID).Scan(&st.Invited, &st.Paid, &st.Rewarded, &st.Days, &st.Bank)
	return st, err
}

// Run keeps the programme going: payments found, rewards given after Hold, refunds taken
// back, banked days handed out.
func (s *Service) Run(ctx context.Context) {
	tick := time.NewTicker(5 * time.Minute)
	defer tick.Stop()
	for {
		if err := s.Process(ctx); err != nil && ctx.Err() == nil {
			s.d.Log.Warn("referral: process", "err", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-tick.C:
		}
	}
}

// Process is one pass of Run.
func (s *Service) Process(ctx context.Context) error {
	if err := s.ensureSchema(ctx); err != nil {
		return err
	}
	dbx := s.d.Store.DB
	if _, err := dbx.ExecContext(ctx, `UPDATE aoi_referrals r SET status = 'trial_started'
		WHERE status = 'pending' AND EXISTS (SELECT 1 FROM trials t WHERE t.tg_id = r.referred_tg)`); err != nil {
		return err
	}
	// The first payment for a tariff after the referral was made, applied.
	if _, err := dbx.ExecContext(ctx, `UPDATE aoi_referrals r SET status = 'paid', payment_id = p.id, paid_at = p.at
		FROM (SELECT DISTINCT ON (r2.id) r2.id AS rid, pay.id, COALESCE(pay.paid_at, pay.created_at) AS at
		      FROM aoi_referrals r2 JOIN payments pay ON pay.tg_id = r2.referred_tg
		      WHERE r2.status IN ('pending', 'trial_started') AND pay.status = 'applied'
		        AND pay.kind IN ('new', 'renew') AND COALESCE(pay.paid_at, pay.created_at) >= r2.created_at
		      ORDER BY r2.id, COALESCE(pay.paid_at, pay.created_at)) p
		WHERE r.id = p.rid`); err != nil {
		return err
	}
	var errs []error
	due := s.d.Now().Add(-s.Hold).Unix()
	for _, id := range s.ids(ctx, &errs, "SELECT id FROM aoi_referrals WHERE status = 'paid' AND created_at <= $1", due) {
		errs = append(errs, s.reward(ctx, id))
	}
	for _, id := range s.ids(ctx, &errs, `SELECT r.id FROM aoi_referrals r JOIN payments p ON p.id = r.payment_id
		WHERE r.status = 'rewarded' AND p.status = 'refunded'`) {
		errs = append(errs, s.reverse(ctx, id))
	}
	for _, tg := range s.ids(ctx, &errs, "SELECT tg_id FROM aoi_ref_bank WHERE days > 0") {
		errs = append(errs, s.payBank(ctx, tg))
	}
	return errors.Join(errs...)
}

func (s *Service) ids(ctx context.Context, errs *[]error, query string, args ...any) []int64 {
	rows, err := s.d.Store.DB.QueryContext(ctx, query, args...)
	if err != nil {
		*errs = append(*errs, err)
		return nil
	}
	defer rows.Close()
	var out []int64
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			*errs = append(*errs, err)
			return out
		}
		out = append(out, id)
	}
	if err := rows.Err(); err != nil {
		*errs = append(*errs, err)
	}
	return out
}

// tx runs fn in a serializable transaction, again on a conflict; then tells the nodes.
func (s *Service) tx(ctx context.Context, fn func(tx *sql.Tx, q *db.Queries) error) error {
	for attempt := 0; ; attempt++ {
		err := func() error {
			tx, err := s.d.Store.DB.BeginTx(ctx, &sql.TxOptions{Isolation: sql.LevelSerializable})
			if err != nil {
				return err
			}
			defer tx.Rollback()
			if err := fn(tx, db.New(tx)); err != nil {
				return err
			}
			return tx.Commit()
		}()
		var pe *pgconn.PgError
		if err == nil || attempt == 7 || !errors.As(err, &pe) || pe.Code != "40001" && pe.Code != "40P01" {
			return err
		}
		time.Sleep(time.Duration(10<<attempt) * time.Millisecond)
	}
}

// target is the referrer's subscription the days go to: the one its chat shows, else the
// one that ends last. Disabled and endless ones take no days.
func target(ctx context.Context, tx *sql.Tx, tg int64) (int64, bool, error) {
	var id int64
	err := tx.QueryRowContext(ctx, `SELECT u.id FROM tg_links l JOIN users u ON u.id = l.user_id
		LEFT JOIN tg_chats c ON c.tg_id = l.tg_id
		WHERE l.tg_id = $1 AND u.status <> 'disabled' AND u.expires_at IS NOT NULL
		ORDER BY (u.id = c.current) DESC NULLS LAST, u.expires_at DESC LIMIT 1`, tg).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, false, nil
	}
	return id, err == nil, err
}

func (s *Service) reward(ctx context.Context, id int64) error {
	var referrer, days int64
	var toUser sql.NullInt64
	done := false
	err := s.tx(ctx, func(tx *sql.Tx, q *db.Queries) error {
		done, toUser = false, sql.NullInt64{}
		var status string
		if err := tx.QueryRowContext(ctx, "SELECT referrer_tg, status FROM aoi_referrals WHERE id = $1 FOR UPDATE", id).
			Scan(&referrer, &status); err != nil {
			return err
		}
		if status != StatePaid {
			return nil
		}
		days = s.RewardDays
		now := s.d.Now().Unix()
		uid, ok, err := target(ctx, tx, referrer)
		if err != nil {
			return err
		}
		if ok {
			if _, err := s.d.Users.ExtendOn(ctx, q, uid, days); err != nil {
				return err
			}
			toUser = sql.NullInt64{Int64: uid, Valid: true}
		} else if _, err := tx.ExecContext(ctx, `INSERT INTO aoi_ref_bank (tg_id, days, updated_at) VALUES ($1, $2, $3)
			ON CONFLICT (tg_id) DO UPDATE SET days = aoi_ref_bank.days + excluded.days, updated_at = excluded.updated_at`,
			referrer, days, now); err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, `UPDATE aoi_referrals SET status = 'rewarded', rewarded_at = $1,
			reward_user_id = $2, reward_days = $3 WHERE id = $4`, now, toUser, days, id); err != nil {
			return err
		}
		done = true
		return nil
	})
	if err != nil || !done {
		return err
	}
	s.d.Users.Changed()
	s.d.Log.Info("referral: rewarded", "referral", id, "referrer", referrer, "days", days, "user", toUser.Int64)
	if s.d.Notify != nil {
		text := "🎉 <b>+" + plural(days) + "</b> за оплату приглашённого друга!\n\nБонус добавлен к подписке."
		if !toUser.Valid {
			text = "🎉 <b>+" + plural(days) + "</b> за оплату приглашённого друга!\n\nБонус сохранён и добавится к подписке, как только она появится."
		}
		s.d.Notify(ctx, referrer, text)
	}
	return nil
}

// reverse takes the days of a refunded first payment back.
func (s *Service) reverse(ctx context.Context, id int64) error {
	var referrer, days int64
	err := s.tx(ctx, func(tx *sql.Tx, q *db.Queries) error {
		var status string
		var toUser sql.NullInt64
		if err := tx.QueryRowContext(ctx, `SELECT referrer_tg, status, reward_user_id, reward_days
			FROM aoi_referrals WHERE id = $1 FOR UPDATE`, id).Scan(&referrer, &status, &toUser, &days); err != nil {
			return err
		}
		if status != StateRewarded {
			days = 0
			return nil
		}
		now := s.d.Now().Unix()
		if toUser.Valid {
			// Not past now: the subscriber keeps what was paid for by others.
			if _, err := tx.ExecContext(ctx, `UPDATE users SET expires_at = GREATEST(expires_at - $1, $2), updated_at = $2
				WHERE id = $3 AND expires_at IS NOT NULL`, days*86400, now, toUser.Int64); err != nil {
				return err
			}
		} else if _, err := tx.ExecContext(ctx, "UPDATE aoi_ref_bank SET days = GREATEST(days - $1, 0), updated_at = $2 WHERE tg_id = $3",
			days, now, referrer); err != nil {
			return err
		}
		_, err := tx.ExecContext(ctx, "UPDATE aoi_referrals SET status = 'ineligible' WHERE id = $1", id)
		return err
	})
	if err == nil && days > 0 {
		s.d.Users.Changed()
		s.d.Log.Warn("referral: reversed after a refund", "referral", id, "referrer", referrer, "days", days)
	}
	return err
}

// payBank hands the banked days to the account's subscription once it has one.
func (s *Service) payBank(ctx context.Context, tg int64) error {
	var days int64
	err := s.tx(ctx, func(tx *sql.Tx, q *db.Queries) error {
		days = 0
		if err := tx.QueryRowContext(ctx, "SELECT days FROM aoi_ref_bank WHERE tg_id = $1 FOR UPDATE", tg).Scan(&days); err != nil {
			return err
		}
		uid, ok, err := target(ctx, tx, tg)
		if err != nil || !ok || days <= 0 {
			days = 0
			return err
		}
		if _, err := s.d.Users.ExtendOn(ctx, q, uid, days); err != nil {
			return err
		}
		_, err = tx.ExecContext(ctx, "UPDATE aoi_ref_bank SET days = 0, updated_at = $1 WHERE tg_id = $2", s.d.Now().Unix(), tg)
		return err
	})
	if err == nil && days > 0 {
		s.d.Users.Changed()
		s.d.Log.Info("referral: bank paid out", "tg", tg, "days", days)
		if s.d.Notify != nil {
			s.d.Notify(ctx, tg, "🎁 К подписке добавлено <b>"+plural(days)+"</b> — бонус за приглашённых друзей.")
		}
	}
	return err
}

// plural is "N дней" with the right ending.
func plural(n int64) string {
	m := n % 100
	word := "дней"
	switch {
	case m >= 11 && m <= 19:
	case m%10 == 1:
		word = "день"
	case m%10 >= 2 && m%10 <= 4:
		word = "дня"
	}
	return strings.TrimSpace(big.NewInt(n).String() + " " + word)
}
