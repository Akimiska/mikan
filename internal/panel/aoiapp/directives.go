// Directives are what the admin tells the installed apps to do with their profiles: move
// the subscription links to another address, add or remove a subscription, update them
// now, show a message. An app asks for its directives at start and from time to time,
// carries them out and reports each one back; a directive is given to an install once.
//
// A directive is meant for every install, for the installs of one subscription (an install
// is counted as one when a profile of it leads to the subscription, or it paid for it) or
// for one install.
type Directives struct {
	st  *store.Store
	now func() time.Time

	mu       sync.Mutex
	schemaOK bool
}

func NewDirectives(st *store.Store, now func() time.Time) *Directives {
	if now == nil {
		now = time.Now
	}
	return &Directives{st: st, now: now}
}

const directivesSchema = `
CREATE TABLE IF NOT EXISTS aoi_app_directives (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        TEXT NOT NULL,             -- rewrite_url | add_profile | remove_profile | refresh | message
  params      TEXT NOT NULL DEFAULT '{}', -- JSON, by kind
  target      TEXT NOT NULL,             -- all | user | app
  target_user BIGINT,
  target_app  TEXT,
  note        TEXT NOT NULL DEFAULT '',
  created_at  BIGINT NOT NULL,
  expires_at  BIGINT,
  canceled_at BIGINT
);
CREATE TABLE IF NOT EXISTS aoi_app_directive_acks (
  directive_id BIGINT NOT NULL,
  app_id       TEXT NOT NULL,
  status       TEXT NOT NULL,             -- done | failed | skipped
  detail       TEXT NOT NULL DEFAULT '',
  at           BIGINT NOT NULL,
  PRIMARY KEY (directive_id, app_id)
);
CREATE TABLE IF NOT EXISTS aoi_app_seen (
  app_id      TEXT PRIMARY KEY,
  first_seen  BIGINT NOT NULL,
  last_seen   BIGINT NOT NULL,
  app_version TEXT NOT NULL DEFAULT '',
  platform    TEXT NOT NULL DEFAULT '',
  profiles    INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS aoi_app_seen_users (
  app_id  TEXT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (app_id, user_id)
);
CREATE INDEX IF NOT EXISTS aoi_app_seen_users_user ON aoi_app_seen_users (user_id);
`

func (d *Directives) ensure(ctx context.Context) error {
	d.mu.Lock()
	defer d.mu.Unlock()
	if d.schemaOK {
		return nil
	}
	if _, err := d.st.DB.ExecContext(ctx, directivesSchema); err != nil {
		return err
	}
	d.schemaOK = true
	return nil
}

// Directive kinds.
const (
	KindRewriteURL    = "rewrite_url"
	KindAddProfile    = "add_profile"
	KindRemoveProfile = "remove_profile"
	KindRefresh       = "refresh"
	KindMessage       = "message"
)

// DirectiveParams are what a directive carries; which fields count depends on its kind.
type DirectiveParams struct {
	// rewrite_url: a profile link that starts with From starts with To instead.
	From string `json:"from,omitempty"`
	To   string `json:"to,omitempty"`
	// add_profile: the link to add, Label its name in the app.
	URL   string `json:"url,omitempty"`
	Label string `json:"label,omitempty"`
	// remove_profile, refresh: the tokens of the subscription whose profiles it is about (its
	// own and the legacy ones carried over); refresh without them updates every profile.
	// add_profile: a profile with one of them is there already, nothing is added.
	Tokens []string `json:"tokens,omitempty"`
	// message
	Title string `json:"title,omitempty"`
	Text  string `json:"text,omitempty"`
}

// NewDirective is a directive the admin sends.
type NewDirective struct {
	Kind    string
	Params  DirectiveParams
	Target  string // all | user | app
	UserID  int64
	AppID   string
	Note    string
	Expires time.Duration // 0: until canceled
}

// Directive is a sent directive with what became of it.
type Directive struct {
	ID         int64           `json:"id"`
	Kind       string          `json:"kind"`
	Params     DirectiveParams `json:"params"`
	Target     string          `json:"target"`
	UserID     int64           `json:"user_id,omitempty"`
	AppID      string          `json:"app_id,omitempty"`
	Note       string          `json:"note"`
	CreatedAt  int64           `json:"created_at"`
	ExpiresAt  int64           `json:"expires_at,omitempty"`
	CanceledAt int64           `json:"canceled_at,omitempty"`
	Done       int64           `json:"done"`
	Failed     int64           `json:"failed"`
	Skipped    int64           `json:"skipped"`
}

// Ack is one install's report on a directive.
type Ack struct {
	AppID  string `json:"app_id"`
	Status string `json:"status"`
	Detail string `json:"detail"`
	At     int64  `json:"at"`
}

// Install is an app install as the panel last saw it.
type Install struct {
	AppID      string  `json:"app_id"`
	FirstSeen  int64   `json:"first_seen"`
	LastSeen   int64   `json:"last_seen"`
	AppVersion string  `json:"app_version"`
	Platform   string  `json:"platform"`
	Profiles   int64   `json:"profiles"`
	UserIDs    []int64 `json:"user_ids"`
}

// DirectiveError is a directive the admin cannot send; Code is the API's error code.
type DirectiveError struct{ Code string }

func (e *DirectiveError) Error() string { return e.Code }

func directiveErr(code string) error { return &DirectiveError{Code: code} }

// linkPrefix: an absolute http(s) address.
func linkPrefix(s string) bool {
	u, err := url.Parse(s)
	return err == nil && (u.Scheme == "https" || u.Scheme == "http") && u.Host != ""
}

func (n *NewDirective) check() error {
	p := &n.Params
	p.From, p.To, p.URL, p.Label = strings.TrimSpace(p.From), strings.TrimSpace(p.To), strings.TrimSpace(p.URL), strings.TrimSpace(p.Label)
	p.Title, p.Text = strings.TrimSpace(p.Title), strings.TrimSpace(p.Text)
	var tokens []string
	for _, t := range p.Tokens {
		if t = normalizeToken(t); t != "" && !slices.Contains(tokens, t) {
			tokens = append(tokens, t)
		}
	}
	p.Tokens = tokens
	switch n.Kind {
	case KindRewriteURL:
		if !linkPrefix(p.From) || !linkPrefix(p.To) {
			return directiveErr("directive_bad_rewrite")
		}
		if p.From == p.To {
			return directiveErr("directive_bad_rewrite")
		}
		*p = DirectiveParams{From: p.From, To: p.To}
	case KindAddProfile:
		if !linkPrefix(p.URL) {
			return directiveErr("directive_bad_url")
		}
		*p = DirectiveParams{URL: p.URL, Label: p.Label, Tokens: p.Tokens}
	case KindRemoveProfile:
		if len(p.Tokens) == 0 {
			return directiveErr("directive_no_subscription")
		}
		*p = DirectiveParams{Tokens: p.Tokens}
	case KindRefresh:
		*p = DirectiveParams{Tokens: p.Tokens}
	case KindMessage:
		if p.Text == "" {
			return directiveErr("directive_empty_text")
		}
		*p = DirectiveParams{Title: p.Title, Text: p.Text}
	default:
		return directiveErr("directive_bad_kind")
	}
	switch n.Target {
	case "all":
		n.UserID, n.AppID = 0, ""
	case "user":
		if n.UserID <= 0 {
			return directiveErr("directive_no_subscription")
		}
		n.AppID = ""
	case "app":
		if !validAppID(n.AppID) {
			return directiveErr("directive_bad_app_id")
		}
		n.UserID = 0
	default:
		return directiveErr("directive_bad_target")
	}
	return nil
}

func nullInt(v int64) sql.NullInt64 { return sql.NullInt64{Int64: v, Valid: v != 0} }

func nullStr(v string) sql.NullString { return sql.NullString{String: v, Valid: v != ""} }

// Create stores a directive; the apps pick it up on their next ask.
func (d *Directives) Create(ctx context.Context, n NewDirective) (Directive, error) {
	if err := d.ensure(ctx); err != nil {
		return Directive{}, err
	}
	if err := n.check(); err != nil {
		return Directive{}, err
	}
	params, _ := json.Marshal(n.Params)
	now := d.now().Unix()
	var expires int64
	if n.Expires > 0 {
		expires = now + int64(n.Expires/time.Second)
	}
	var id int64
	err := d.st.DB.QueryRowContext(ctx,
		`INSERT INTO aoi_app_directives (kind, params, target, target_user, target_app, note, created_at, expires_at)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8) RETURNING id`,
		n.Kind, string(params), n.Target, nullInt(n.UserID), nullStr(n.AppID), strings.TrimSpace(n.Note), now, nullInt(expires)).Scan(&id)
	if err != nil {
		return Directive{}, err
	}
	return d.Get(ctx, id)
}

const directiveCols = `d.id, d.kind, d.params, d.target, COALESCE(d.target_user, 0), COALESCE(d.target_app, ''), d.note,
  d.created_at, COALESCE(d.expires_at, 0), COALESCE(d.canceled_at, 0),
  (SELECT count(*) FROM aoi_app_directive_acks a WHERE a.directive_id = d.id AND a.status = 'done'),
  (SELECT count(*) FROM aoi_app_directive_acks a WHERE a.directive_id = d.id AND a.status = 'failed'),
  (SELECT count(*) FROM aoi_app_directive_acks a WHERE a.directive_id = d.id AND a.status = 'skipped')`

func scanDirective(row interface{ Scan(...any) error }) (Directive, error) {
	var v Directive
	var params string
	if err := row.Scan(&v.ID, &v.Kind, &params, &v.Target, &v.UserID, &v.AppID, &v.Note,
		&v.CreatedAt, &v.ExpiresAt, &v.CanceledAt, &v.Done, &v.Failed, &v.Skipped); err != nil {
		return v, err
	}
	_ = json.Unmarshal([]byte(params), &v.Params)
	return v, nil
}

func (d *Directives) Get(ctx context.Context, id int64) (Directive, error) {
	if err := d.ensure(ctx); err != nil {
		return Directive{}, err
	}
	return scanDirective(d.st.DB.QueryRowContext(ctx, "SELECT "+directiveCols+" FROM aoi_app_directives d WHERE d.id = $1", id))
}

// List is the directives newest first.
func (d *Directives) List(ctx context.Context, limit, offset int64) ([]Directive, int64, error) {
	if err := d.ensure(ctx); err != nil {
		return nil, 0, err
	}
	var total int64
	if err := d.st.DB.QueryRowContext(ctx, "SELECT count(*) FROM aoi_app_directives").Scan(&total); err != nil {
		return nil, 0, err
	}
	rows, err := d.st.DB.QueryContext(ctx, "SELECT "+directiveCols+" FROM aoi_app_directives d ORDER BY d.id DESC LIMIT $1 OFFSET $2", limit, offset)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()
	out := []Directive{}
	for rows.Next() {
		v, err := scanDirective(rows)
		if err != nil {
			return nil, 0, err
		}
		out = append(out, v)
	}
	return out, total, rows.Err()
}

// Cancel stops giving a directive out; the installs that carried it out stay as they are.
func (d *Directives) Cancel(ctx context.Context, id int64) (Directive, error) {
	if err := d.ensure(ctx); err != nil {
		return Directive{}, err
	}
	res, err := d.st.DB.ExecContext(ctx, "UPDATE aoi_app_directives SET canceled_at = $2 WHERE id = $1 AND canceled_at IS NULL", id, d.now().Unix())
	if err != nil {
		return Directive{}, err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		if _, err := d.Get(ctx, id); err != nil {
			return Directive{}, err
		}
	}
	return d.Get(ctx, id)
}

// Acks are the installs' reports on a directive, newest first.
func (d *Directives) Acks(ctx context.Context, id int64) ([]Ack, error) {
	if err := d.ensure(ctx); err != nil {
		return nil, err
	}
	rows, err := d.st.DB.QueryContext(ctx, "SELECT app_id, status, detail, at FROM aoi_app_directive_acks WHERE directive_id = $1 ORDER BY at DESC LIMIT 500", id)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Ack{}
	for rows.Next() {
		var a Ack
		if err := rows.Scan(&a.AppID, &a.Status, &a.Detail, &a.At); err != nil {
			return nil, err
		}
		out = append(out, a)
	}
	return out, rows.Err()
}

// Installs are the installs seen, latest first: of one subscription (userID), by a part of
// the app_id (q), or all.
func (d *Directives) Installs(ctx context.Context, userID int64, q string, limit int64) ([]Install, error) {
	if err := d.ensure(ctx); err != nil {
		return nil, err
	}
	q = strings.ToLower(strings.TrimSpace(q))
	rows, err := d.st.DB.QueryContext(ctx, `
		SELECT s.app_id, s.first_seen, s.last_seen, s.app_version, s.platform, s.profiles,
		       COALESCE((SELECT string_agg(u.user_id::text, ',' ORDER BY u.user_id) FROM aoi_app_seen_users u WHERE u.app_id = s.app_id), '')
		FROM aoi_app_seen s
		WHERE ($1 = 0 OR EXISTS (SELECT 1 FROM aoi_app_seen_users u WHERE u.app_id = s.app_id AND u.user_id = $1))
		  AND ($2 = '' OR s.app_id LIKE '%' || $2 || '%')
		ORDER BY s.last_seen DESC LIMIT $3`, userID, q, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Install{}
	for rows.Next() {
		var in Install
		var users string
		if err := rows.Scan(&in.AppID, &in.FirstSeen, &in.LastSeen, &in.AppVersion, &in.Platform, &in.Profiles, &users); err != nil {
			return nil, err
		}
		in.UserIDs = []int64{}
		for _, s := range strings.Split(users, ",") {
			var id int64
			if _, err := fmt.Sscan(s, &id); err == nil {
				in.UserIDs = append(in.UserIDs, id)
			}
		}
		out = append(out, in)
	}
	return out, rows.Err()
}

// pendingItem is a directive as the app gets it.
type pendingItem struct {
	ID     int64           `json:"id"`
	Kind   string          `json:"kind"`
	Params DirectiveParams `json:"params"`
}

// seen records the install and the subscriptions its profiles lead to (they are the whole
// set: a profile removed in the app drops its subscription here).
func (d *Directives) seen(ctx context.Context, appID, version, platform string, profiles int, users []int64) error {
	now := d.now().Unix()
	tx, err := d.st.DB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	if _, err := tx.ExecContext(ctx, `
		INSERT INTO aoi_app_seen (app_id, first_seen, last_seen, app_version, platform, profiles) VALUES ($1, $2, $2, $3, $4, $5)
		ON CONFLICT (app_id) DO UPDATE SET last_seen = $2, app_version = $3, platform = $4, profiles = $5`,
		appID, now, version, platform, profiles); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, "DELETE FROM aoi_app_seen_users WHERE app_id = $1", appID); err != nil {
		return err
	}
	for _, u := range users {
		if _, err := tx.ExecContext(ctx, "INSERT INTO aoi_app_seen_users (app_id, user_id) VALUES ($1, $2) ON CONFLICT DO NOTHING", appID, u); err != nil {
			return err
		}
	}
	return tx.Commit()
}

// pending are the directives the install has not reported on, oldest first.
func (d *Directives) pending(ctx context.Context, appID string) ([]pendingItem, error) {
	rows, err := d.st.DB.QueryContext(ctx, `
		SELECT d.id, d.kind, d.params FROM aoi_app_directives d
		WHERE d.canceled_at IS NULL AND (d.expires_at IS NULL OR d.expires_at > $2)
		  AND (d.target = 'all'
		       OR (d.target = 'app' AND d.target_app = $1)
		       OR (d.target = 'user' AND (
		             d.target_user IN (SELECT user_id FROM aoi_app_seen_users WHERE app_id = $1)
		             OR d.target_user IN (SELECT user_id FROM aoi_app_orders WHERE app_id = $1 AND user_id IS NOT NULL))))
		  AND NOT EXISTS (SELECT 1 FROM aoi_app_directive_acks a WHERE a.directive_id = d.id AND a.app_id = $1)
		ORDER BY d.id LIMIT 20`, appID, d.now().Unix())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []pendingItem{}
	for rows.Next() {
		var it pendingItem
		var params string
		if err := rows.Scan(&it.ID, &it.Kind, &params); err != nil {
			return nil, err
		}
		_ = json.Unmarshal([]byte(params), &it.Params)
		out = append(out, it)
	}
	return out, rows.Err()
}

func (d *Directives) ack(ctx context.Context, appID string, id int64, status, detail string) error {
	_, err := d.st.DB.ExecContext(ctx, `
		INSERT INTO aoi_app_directive_acks (directive_id, app_id, status, detail, at)
		SELECT $1, $2, $3, $4, $5 WHERE EXISTS (SELECT 1 FROM aoi_app_directives WHERE id = $1)
		ON CONFLICT (directive_id, app_id) DO UPDATE SET status = $3, detail = $4, at = $5`,
		id, appID, status, detail, d.now().Unix())
	return err
}

