// directivesGet is GET app/directives?app_id=&tokens=&v=&os=&profiles=: the install says
// what it holds and gets what it has to do.
func (h *Handler) directivesGet(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	q := r.URL.Query()
	appID := strings.TrimSpace(q.Get("app_id"))
	if !validAppID(appID) {
		writeJSON(w, http.StatusBadRequest, map[string]any{"ok": false, "error": "invalid_app_id"})
		return
	}
	var users []int64
	seenTok := 0
	for _, part := range strings.Split(strings.Join(q["tokens"], ","), ",") {
		t := normalizeToken(part)
		if t == "" {
			continue
		}
		if seenTok++; seenTok > maxTokens {
			break
		}
		if u, err := h.resolveToken(ctx, t); err == nil && !slices.Contains(users, u.ID) {
			users = append(users, u.ID)
		}
	}
	profiles, _ := strconv.Atoi(q.Get("profiles"))
	if err := h.dirs.ensure(ctx); err != nil {
		h.d.Log.Error("aoiapp: directives schema", "err", err)
		writeJSON(w, http.StatusServiceUnavailable, map[string]any{"ok": false, "error": "internal"})
		return
	}
	if err := h.dirs.seen(ctx, appID, clip(q.Get("v"), 32), clip(q.Get("os"), 16), max(0, min(profiles, 1000)), users); err != nil {
		h.d.Log.Warn("aoiapp: directives seen", "err", err)
	}
	items, err := h.dirs.pending(ctx, appID)
	if err != nil {
		h.d.Log.Error("aoiapp: directives", "err", err)
		writeJSON(w, http.StatusServiceUnavailable, map[string]any{"ok": false, "error": "internal"})
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "items": items})
}

// directiveAck is POST app/directive-ack {app_id, results: [{id, status, detail}]}.
func (h *Handler) directiveAck(w http.ResponseWriter, r *http.Request) {
	var in struct {
		AppID   string `json:"app_id"`
		Results []struct {
			ID     int64  `json:"id"`
			Status string `json:"status"`
			Detail string `json:"detail"`
		} `json:"results"`
	}
	body, _ := io.ReadAll(io.LimitReader(r.Body, 32<<10))
	if err := json.Unmarshal(body, &in); err != nil || !validAppID(in.AppID) {
		writeJSON(w, http.StatusBadRequest, map[string]any{"ok": false, "error": "invalid_app_id"})
		return
	}
	if err := h.dirs.ensure(r.Context()); err != nil {
		writeJSON(w, http.StatusServiceUnavailable, map[string]any{"ok": false, "error": "internal"})
		return
	}
	for i, res := range in.Results {
		if i >= 20 {
			break
		}
		st := res.Status
		if st != "done" && st != "failed" && st != "skipped" {
			continue
		}
		if err := h.dirs.ack(r.Context(), in.AppID, res.ID, st, strings.ToValidUTF8(clip(res.Detail, 300), "")); err != nil {
			h.d.Log.Warn("aoiapp: directive ack", "err", err)
			writeJSON(w, http.StatusServiceUnavailable, map[string]any{"ok": false, "error": "store_failed"})
			return
		}
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true})
}

// UserTokens are a subscription's tokens: its own first, then the legacy ones that lead to
// it. sql.ErrNoRows: no such subscription.
func (d *Directives) UserTokens(ctx context.Context, userID int64) ([]string, error) {
	var own string
	if err := d.st.DB.QueryRowContext(ctx, "SELECT sub_token FROM users WHERE id = $1", userID).Scan(&own); err != nil {
		return nil, err
	}
	out := []string{}
	if own != "" {
		out = append(out, own)
	}
	rows, err := d.st.DB.QueryContext(ctx, "SELECT token FROM legacy_sub_tokens WHERE user_id = $1", userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		var t string
		if err := rows.Scan(&t); err != nil {
			return nil, err
		}
		if !slices.Contains(out, t) {
			out = append(out, t)
		}
	}
	return out, rows.Err()
}
