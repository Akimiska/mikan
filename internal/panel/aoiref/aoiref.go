// Package aoiref is the AoiVPN fork's referral programme, carried over from the legacy
// Python bot (vpn-bot/lib/referral_service.py) with its rules:
//
//   - every Telegram account has a code; its link is t.me/<bot>?start=ref-<code> (the
//     legacy links already shared keep working: the codes are imported as they were);
//   - an account that has nothing yet (no subscription, no trial, no payment) and starts
//     the bot by such a link becomes the code owner's referral; it takes the usual trial;
//   - its first payment for a tariff gives the referrer RewardDays days, no sooner than
//     Hold after the referral was made (an account made to farm the bonus has to wait);
//     the days go to the referrer's subscription, or wait in its bank until it has one;
//   - that payment refunded takes the days back.
//
// The fork's tables (aoi_ref_*, aoi_referrals) are created here, not by the upstream
// migrations, so a merge of upstream never meets them.
package aoiref

